function drink(id, category, name, price, extra = {}) {
  const sizes = extra.sizes || []
  const addons = extra.addons === undefined ? DRINK_ADDONS : extra.addons
  return {
    id,
    category,
    name,
    price,
    description: extra.description || '',
    emoji: extra.emoji || '🧋',
    popular: !!extra.popular,
    available: true,
    kind: 'drink',
    sugar: extra.sugar !== false,
    ice: extra.ice !== false,
    spice: false,
    sizes: sizes.map((size) => ({ ...size })),
    addons: addons.map((addon) => ({ ...addon })),
    image: extra.image || '',
  }
}

function food(id, category, name, price, extra = {}) {
  return {
    id,
    category,
    name,
    price,
    description: extra.description || '',
    emoji: extra.emoji || '🍽️',
    popular: !!extra.popular,
    available: true,
    kind: extra.kind || 'food',
    sugar: false,
    ice: false,
    spice: false,
    sizes: (extra.sizes || []).map((size) => ({ ...size })),
    addons: [],
    image: extra.image || '',
  }
}

