export function photoFor(item) {
  return BY_ID[item.id] || BY_CATEGORY[item.category] || ''
}

export function withMenuPhotos(items) {
  return items.map((item) => {
    const image = photoFor(item)
    return image ? { ...item, image } : item
  })
}
